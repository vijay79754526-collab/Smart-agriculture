  const textSources = new WeakMap();
  const attributeSources = new WeakMap();

  function getLanguage() {
    return localStorage.getItem("agri-language") || "en";
  }

  function translate(value, language = getLanguage()) {
    return translations[language]?.[value] || value;
  }

  function format(template, values, language = getLanguage()) {
    return Object.entries(values).reduce(
      (result, [key, value]) => result.replaceAll(`{${key}}`, value),
      translate(template, language)
    );
  }

  function applyLanguage(language = getLanguage()) {
    localStorage.setItem("agri-language", language);
    document.documentElement.lang = language === "kn" ? "kn" : language;
    document.title = translate(originalTitle, language);

    document.querySelectorAll("[data-translation-source]").forEach(element => {
      element.textContent = translate(element.dataset.translationSource, language);
    });

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    let textNode;
    while ((textNode = walker.nextNode())) {
      if (!textSources.has(textNode)) textSources.set(textNode, textNode.nodeValue);
      const source = textSources.get(textNode);
      const leading = source.match(/^\s*/)[0];
      const trailing = source.match(/\s*$/)[0];
      const content = source.slice(leading.length, source.length - trailing.length || undefined);
      textNode.nodeValue = `${leading}${translate(content, language)}${trailing}`;
    }

    document.querySelectorAll("[placeholder], [aria-label], option").forEach(element => {
      let sources = attributeSources.get(element);
      if (!sources) {
        sources = {};
        attributeSources.set(element, sources);
      }

      ["placeholder", "aria-label"].forEach(attribute => {
        if (element.hasAttribute(attribute)) {
          if (!(attribute in sources)) sources[attribute] = element.getAttribute(attribute);
          element.setAttribute(attribute, translate(sources[attribute], language));
        }
      });
    });

    const languageSelect = document.querySelector("#languageSelect");
    if (languageSelect) languageSelect.value = language;
  }

  function greeting(name) {
    return translate("Welcome, {name}!").replace("{name}", name);
  }

  window.agriI18n = { applyLanguage, format, getLanguage, greeting, translate };

  document.addEventListener("change", event => {
    if (event.target.matches("#languageSelect")) {
      applyLanguage(event.target.value);
      document.dispatchEvent(new CustomEvent("agri-language-change", {
        detail: { language: event.target.value }
      }));
    }
  });
